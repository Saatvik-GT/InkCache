export interface AsciiTextOptions {
  /** Glyph painted for a lit pixel. */
  on?: string;
  /** Glyph painted for an unlit pixel — space keeps the field clean. */
  off?: string;
  /** Blank columns between characters. */
  tracking?: number;
}

/**
 * Render a line of text as a character-grid bitmap. Unknown characters
 * fall back to a space rather than throwing — a headline is decoration,
 * and a missing glyph shouldn't take a page down.
 */
export function renderAsciiText(
  text: string,
  { on = "#", off = " ", tracking = 1 }: AsciiTextOptions = {},
): string {
  const chars = [...text.toUpperCase()];
  const rows: string[] = [];

  for (let y = 0; y < GLYPH_H; y++) {
    let row = "";
    chars.forEach((ch, i) => {
      const bits = GLYPHS[ch] ?? GLYPHS[" "]!;
      for (let x = 0; x < GLYPH_W; x++) {
        row += bits[y * GLYPH_W + x] === "#" ? on : off;
      }
      if (i < chars.length - 1) row += off.repeat(tracking);
    });
    rows.push(row);
  }

  return rows.join("\n");
}

/** Width in characters a given string will occupy once rendered. */
export function asciiTextWidth(text: string, tracking = 1): number {
  const n = [...text].length;
  return n === 0 ? 0 : n * GLYPH_W + (n - 1) * tracking;
}
